import turtle
bob=turtle.Turtle()
def polygon(sides,dist):
    angle=360/sides
    bob.begin_fill()
    for times in range(sides):
        bob.forward(dist)
        bob.left(angle)
    bob.end_fill()

def jump(x,y):
    bob.penup()
    bob.goto(x,y)
    bob.pendown()
def tree1(x,y):
  jump(x,y)
  bob.width(5)
  bob.color("brown")
  polygon(4, 50)
  jump(-25 + x , 50 + y)
  bob.color("white")
  polygon(3, 100)
  jump(-25 + x , 100 + y)
  polygon(3,100)
